#!/usr/bin/env python3
"""The released versions of the docs: one directory per minor under versions/.

  versions.py config         write config/_default/hugo.toml from the directories in versions/
  versions.py check          fail when that file is not current
  versions.py cut VERSION    copy content/ (next) to versions/VERSION and make it the latest

content/ is next, the docs of the coming release; it is built locally but not deployed.
The newest directory in versions/ is the latest release, published at the site root.
"""
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSIONS = ROOT / "versions"
CONFIG = ROOT / "config" / "_default" / "hugo.toml"
NAME = re.compile(r"v(\d+)\.(\d+)")


def released():
    """vX.Y directories in versions/, newest first."""
    names = [p.name for p in VERSIONS.iterdir() if p.is_dir() and NAME.fullmatch(p.name)]
    return sorted(names, key=lambda n: tuple(map(int, NAME.fullmatch(n).groups())), reverse=True)


def render():
    versions = released()
    if not versions:
        sys.exit("versions.py: versions/ has no vX.Y directory")
    out = [
        "# Generated by scripts/versions.py from the directories in versions/; do not edit.",
        f'defaultContentVersion = "{versions[0]}"   # the latest release, at the site root',
        "defaultContentVersionInSubdir = false",
        "",
        "[versions.next]   # content/: the coming release, not deployed (config/production)",
        "  weight = 1",
    ]
    for i, v in enumerate(versions, start=2):
        out += [f'[versions."{v}"]', f"  weight = {i}"]
    for source, version in [("content", "next")] + [(f"versions/{v}", v) for v in versions]:
        out += [
            "",
            "[[module.mounts]]",
            f'  source = "{source}"',
            '  target = "content"',
            "  [module.mounts.sites.matrix]",
            f'    versions = ["{version}"]',
        ]
    return "\n".join(out) + "\n"


def main(args):
    match args:
        case ["config"]:
            CONFIG.parent.mkdir(parents=True, exist_ok=True)
            CONFIG.write_text(render())
        case ["check"]:
            if not CONFIG.exists() or CONFIG.read_text() != render():
                sys.exit(f"versions.py: {CONFIG.relative_to(ROOT)} is stale (run `make versions`)")
        case ["cut", version]:
            if not NAME.fullmatch(version):
                sys.exit(f"versions.py: {version!r} is not vX.Y")
            target = VERSIONS / version
            if target.exists():
                sys.exit(f"versions.py: {target.relative_to(ROOT)} exists; fix released docs there, or remove it to cut again")
            shutil.copytree(ROOT / "content", target)
            CONFIG.write_text(render())
            print(f"cut {version}: versions/{version} is the latest release")
        case _:
            sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
