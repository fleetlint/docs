#!/usr/bin/env python3
"""Check the hand-written rule catalog against the generated rule pages.

content/rules/ is generated by `fleetlint docs` from the catalog; content/rule-catalog.md is
written by hand. This fails when a rule id, severity, tier list, preset or kind in its tables,
or a number in its totals, differs from the generated pages, or when a rule is missing or extra.
"""
import os
import re
import sys

content = sys.argv[1] if len(sys.argv) > 1 else "content"
CATALOG = os.path.join(content, "rule-catalog.md")
RULES = os.path.join(content, "rules")
ID = r"[a-z0-9-]+(?:/[a-z0-9-]+)+"


def tables(path):
    """Yield (heading, header, rows) per Markdown table; a row is (line number, cells)."""
    heading, table = "", None
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    for n, line in enumerate(lines + [""], 1):
        if line.startswith("|"):
            # Escaped pipes (`a\|b`) stay inside their cell.
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]]
            if table is None:
                table = (heading, cells, [])
            elif not set("".join(cells)) <= set("-: "):
                table[2].append((n, cells))
            continue
        if table is not None:
            yield table
            table = None
        if line.startswith("#"):
            heading = line.lstrip("#").strip()


def column(header, name, where):
    if name not in header:
        sys.exit(f"{where}: the table has no {name} column")
    return header.index(name)


def generated():
    """The rules the generated index lists, with the kind and artifact row of each page."""
    names = [os.path.join(RULES, p) for p in ("_index.md", "README.md")]
    index = next((p for p in names if os.path.exists(p)), None)
    if index is None:
        sys.exit(f"{RULES}: no rule index; run `make gen`")
    rules = {}
    for _, header, rows in tables(index):
        if not {"Rule", "Severity", "Tiers", "Preset"} <= set(header):
            continue
        cols = {k: header.index(k) for k in ("Rule", "Severity", "Tiers", "Preset")}
        for n, row in rows:
            link = re.match(r"\[(" + ID + r")\]", row[cols["Rule"]])
            if not link:
                sys.exit(f"{index}:{n}: no rule link in the Rule column")
            rules[link.group(1)] = {k.lower(): row[cols[k]] for k in ("Severity", "Tiers", "Preset")}
    if not rules:
        sys.exit(f"{index}: no rule table")
    for rid, rule in rules.items():
        page = os.path.join(RULES, rid.replace("/", "--") + ".md")
        rows = {}
        for _, header, body in tables(page):
            rows.update({cells[0]: cells[1] for _, cells in [(0, header)] + body if len(cells) == 2})
        rule["kind"] = rows.get("Kind", "")
        rule["artifact"] = "Artifact" in rows
    return rules


def main():
    rules = generated()
    caps = {r for r, v in rules.items() if v["kind"] == "capability"}
    impls = {r for r in rules if r.rsplit("/", 1)[0] in caps}
    # A not-applicable implementation's short page has no Artifact row; its capability decides.
    by_artifact = {r.rsplit("/", 1)[0] for r in impls if rules[r]["artifact"]}
    top = set(rules) - impls
    totals = {
        "rules": len(top),
        "of which capabilities": len(caps),
        "of which keyed by artifact": len(by_artifact),
        "implementations per stack (and `any`)": sum(1 for r in impls if r.rsplit("/", 1)[0] not in by_artifact),
        "implementations per artifact kind": sum(1 for r in impls if r.rsplit("/", 1)[0] in by_artifact),
    }

    errors, seen = [], {}
    for heading, header, rows in tables(CATALOG):
        if heading == "Totals":
            found = {}
            for n, (label, count, *_) in rows:
                if label not in totals:
                    errors.append(f"{CATALOG}:{n}: unknown total {label!r}")
                elif count != str(totals[label]):
                    errors.append(f"{CATALOG}:{n}: {label} is {count}, the generated pages have {totals[label]}")
                found[label] = n
            errors += [f"{CATALOG}: Totals has no row {label!r}" for label in totals if label not in found]
            continue
        if not header or header[0] != "Rule":
            continue
        cols = {k: column(header, k, f"{CATALOG} ({heading})") for k in ("Severity", "Tiers", "Preset", "Kind")}
        for n, row in rows:
            ids = re.findall(r"`([^`]+)`", row[0])
            if not ids:
                errors.append(f"{CATALOG}:{n}: no rule id in the Rule column")
            for rid in ids:
                if rid in seen:
                    errors.append(f"{CATALOG}:{n}: {rid} is listed again (first on line {seen[rid]})")
                seen[rid] = n
                if rid not in top:
                    errors.append(f"{CATALOG}:{n}: {rid} is not a rule of the generated pages")
                    continue
                want = dict(rules[rid])
                want["kind"] += " by artifact" if rid in by_artifact else ""
                for key, col in cols.items():
                    have = row[col].replace("*", "").replace("`", "").strip()
                    if have != want[key.lower()]:
                        errors.append(f"{CATALOG}:{n}: {rid}: {key} is {have!r}, the generated pages say {want[key.lower()]!r}")
    errors += [f"{CATALOG}: {rid} is missing (a rule of the generated pages)" for rid in sorted(top - set(seen))]

    for line in errors:
        print(line, file=sys.stderr)
    print(f"{len(seen)} rule ids in {CATALOG} checked against {len(rules)} generated pages, {len(errors)} mismatches")
    return 1 if errors else 0


sys.exit(main())
